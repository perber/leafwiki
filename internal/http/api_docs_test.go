// The committed Swagger output under docs/api is generated by `make api-docs`.
// These tests only read it; they never run the generator.

// apiDocsDir locates docs/api relative to this source file, so the tests do not
// depend on the working directory of the test binary.
func apiDocsDir(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate api_docs_test.go")
	}
	return filepath.Join(filepath.Dir(file), "..", "..", "docs", "api")
}

// readAPIDocument decodes docs/api/<filename> (swagger.json or swagger.yaml)
// into a generic map normalized to JSON value types.
func readAPIDocument(t *testing.T, filename string) map[string]any {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(apiDocsDir(t), filename))
	if err != nil {
		t.Fatalf("read %s: %v (run `make api-docs`)", filename, err)
	}

	var doc map[string]any
	switch filepath.Ext(filename) {
	case ".json":
		err = json.Unmarshal(data, &doc)
	case ".yaml", ".yml":
		// Round-trip through JSON so integers, maps and slices have the same
		// dynamic types as the JSON document.
		var raw map[string]any
		if err = yaml.Unmarshal(data, &raw); err == nil {
			var asJSON []byte
			if asJSON, err = json.Marshal(raw); err == nil {
				err = json.Unmarshal(asJSON, &doc)
			}
		}
	default:
		t.Fatalf("unsupported API document extension: %s", filename)
	}
	if err != nil {
		t.Fatalf("decode %s: %v", filename, err)
	}
	return doc
}

// docObject walks nested objects by key and fails if a step is missing.
func docObject(t *testing.T, node map[string]any, path ...string) map[string]any {
	t.Helper()
	cur := node
	for _, key := range path {
		next, ok := cur[key].(map[string]any)
		if !ok {
			t.Fatalf("missing object %q in path %v", key, path)
		}
		cur = next
	}
	return cur
}

func docString(node map[string]any, key string) string {
	s, _ := node[key].(string)
	return s
}

// resolveDefinition follows a "#/definitions/<name>" reference.
func resolveDefinition(t *testing.T, doc map[string]any, schema map[string]any) (string, map[string]any) {
	t.Helper()
	ref := docString(schema, "$ref")
	name, ok := strings.CutPrefix(ref, "#/definitions/")
	if !ok {
		t.Fatalf("schema is not a definitions reference: %v", schema)
	}
	return name, docObject(t, doc, "definitions", name)
}

func TestAPIDocs_Metadata_DescribesExperimentalAPI(t *testing.T) {
	doc := readAPIDocument(t, "swagger.json")

	if got := docString(doc, "swagger"); got != "2.0" {
		t.Errorf("swagger = %q, want 2.0", got)
	}
	info := docObject(t, doc, "info")
	if got := docString(info, "title"); got != "LeafWiki API" {
		t.Errorf("info.title = %q", got)
	}
	if got := docString(info, "version"); got != "0.x" {
		t.Errorf("info.version = %q, want 0.x", got)
	}
	desc := strings.ToLower(docString(info, "description"))
	for _, want := range []string{"incomplete", "before v1", "--enable-api-key-management", "auth"} {
		if !strings.Contains(desc, want) {
			t.Errorf("info.description should mention %q: %q", want, desc)
		}
	}

	if got := docString(doc, "basePath"); got != "/api" {
		t.Errorf("basePath = %q, want /api", got)
	}
	if got := docString(doc, "host"); got != "" {
		t.Errorf("host = %q, want absent", got)
	}
	if schemes, ok := doc["schemes"].([]any); ok && len(schemes) > 0 {
		t.Errorf("schemes = %v, want absent", schemes)
	}
	if sec, ok := doc["security"].([]any); ok && len(sec) > 0 {
		t.Errorf("root security = %v, want absent", sec)
	}

	bearer := docObject(t, doc, "securityDefinitions", "BearerAuth")
	if docString(bearer, "type") != "apiKey" || docString(bearer, "in") != "header" || docString(bearer, "name") != "Authorization" {
		t.Errorf("BearerAuth = %v", bearer)
	}
	if !strings.Contains(docString(bearer, "description"), "Bearer lw_<prefix>_<secret>") {
		t.Errorf("BearerAuth description must show the full header value: %q", docString(bearer, "description"))
	}
}

func TestAPIDocs_Health_IsTheOnlyDocumentedOperation(t *testing.T) {
	doc := readAPIDocument(t, "swagger.json")

	paths := docObject(t, doc, "paths")
	if len(paths) != 1 {
		t.Fatalf("documented paths = %v, want only /health", reflect.ValueOf(paths).MapKeys())
	}
	item := docObject(t, paths, "/health")
	if len(item) != 1 {
		t.Fatalf("/health operations = %v, want only get", reflect.ValueOf(item).MapKeys())
	}
	op := docObject(t, item, "get")

	if tags, _ := op["tags"].([]any); len(tags) != 1 || tags[0] != "health" {
		t.Errorf("tags = %v, want [health]", op["tags"])
	}
	if produces, _ := op["produces"].([]any); len(produces) != 1 || produces[0] != "application/json" {
		t.Errorf("produces = %v", op["produces"])
	}
	if _, ok := op["security"]; ok {
		t.Errorf("health must not require authentication: %v", op["security"])
	}
	if _, ok := op["consumes"]; ok {
		t.Errorf("health has no request body: consumes = %v", op["consumes"])
	}
	if params, _ := op["parameters"].([]any); len(params) != 0 {
		t.Errorf("health has no parameters: %v", params)
	}

	responses := docObject(t, op, "responses")
	if _, ok := responses["403"]; ok {
		t.Error("403 must not be documented for health")
	}

	// 200 -> health model, resolved by reference instead of an assumed name.
	name, health := resolveDefinition(t, doc, docObject(t, responses, "200", "schema"))
	if !strings.HasSuffix(name, "HealthResponse") {
		t.Errorf("200 references %q, want the HealthResponse model", name)
	}
	assertProperty(t, health, "status", "string")
	assertProperty(t, health, "checks", "object")
	if add := docObject(t, docObject(t, health, "properties", "checks"), "additionalProperties"); docString(add, "type") != "string" {
		t.Errorf("checks additionalProperties = %v, want string", add)
	}

	// 401 and 429 -> flat error model.
	for _, status := range []string{"401", "429"} {
		name, legacy := resolveDefinition(t, doc, docObject(t, responses, status, "schema"))
		if !strings.HasSuffix(name, "LegacyError") {
			t.Errorf("%s references %q, want the LegacyError model", status, name)
		}
		assertProperty(t, legacy, "error", "string")
	}

	// 503 -> intentionally broad object that names both real shapes.
	r503 := docObject(t, responses, "503")
	schema := docObject(t, r503, "schema")
	if docString(schema, "type") != "object" {
		t.Errorf("503 schema type = %v, want object", schema["type"])
	}
	if _, ok := schema["$ref"]; ok {
		t.Errorf("503 schema must not reference a single model: %v", schema)
	}
	for _, want := range []string{"HealthResponse", "LegacyError"} {
		if !strings.Contains(docString(r503, "description"), want) {
			t.Errorf("503 description should name %s: %q", want, docString(r503, "description"))
		}
	}
}

func assertProperty(t *testing.T, model map[string]any, name, wantType string) {
	t.Helper()
	prop := docObject(t, model, "properties", name)
	if got := docString(prop, "type"); got != wantType {
		t.Errorf("property %q type = %q, want %q", name, got, wantType)
	}
}

