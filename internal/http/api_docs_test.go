// The committed Swagger output under docs/api is generated by `make api-docs`.
// These tests only read it; they never run the generator.

// apiDocsDir locates docs/api relative to this source file, so the tests do not
// depend on the working directory of the test binary.
func apiDocsDir(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate api_docs_test.go")
	}
	return filepath.Join(filepath.Dir(file), "..", "..", "docs", "api")
}

// readAPIDocument decodes docs/api/<filename> (swagger.json or swagger.yaml)
// into a generic map normalized to JSON value types.
func readAPIDocument(t *testing.T, filename string) map[string]any {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(apiDocsDir(t), filename))
	if err != nil {
		t.Fatalf("read %s: %v (run `make api-docs`)", filename, err)
	}

	var doc map[string]any
	switch filepath.Ext(filename) {
	case ".json":
		err = json.Unmarshal(data, &doc)
	case ".yaml", ".yml":
		// Round-trip through JSON so integers, maps and slices have the same
		// dynamic types as the JSON document.
		var raw map[string]any
		if err = yaml.Unmarshal(data, &raw); err == nil {
			var asJSON []byte
			if asJSON, err = json.Marshal(raw); err == nil {
				err = json.Unmarshal(asJSON, &doc)
			}
		}
	default:
		t.Fatalf("unsupported API document extension: %s", filename)
	}
	if err != nil {
		t.Fatalf("decode %s: %v", filename, err)
	}
	return doc
}

// docObject walks nested objects by key and fails if a step is missing.
func docObject(t *testing.T, node map[string]any, path ...string) map[string]any {
	t.Helper()
	cur := node
	for _, key := range path {
		next, ok := cur[key].(map[string]any)
		if !ok {
			t.Fatalf("missing object %q in path %v", key, path)
		}
		cur = next
	}
	return cur
}

func docString(node map[string]any, key string) string {
	s, _ := node[key].(string)
	return s
}

// resolveDefinition follows a "#/definitions/<name>" reference.
func resolveDefinition(t *testing.T, doc map[string]any, schema map[string]any) (string, map[string]any) {
	t.Helper()
	ref := docString(schema, "$ref")
	name, ok := strings.CutPrefix(ref, "#/definitions/")
	if !ok {
		t.Fatalf("schema is not a definitions reference: %v", schema)
	}
	return name, docObject(t, doc, "definitions", name)
}

func TestAPIDocs_Metadata_DescribesExperimentalAPI(t *testing.T) {
	doc := readAPIDocument(t, "swagger.json")

	if got := docString(doc, "swagger"); got != "2.0" {
		t.Errorf("swagger = %q, want 2.0", got)
	}
	info := docObject(t, doc, "info")
	if got := docString(info, "title"); got != "LeafWiki API" {
		t.Errorf("info.title = %q", got)
	}
	if got := docString(info, "version"); got != "0.x" {
		t.Errorf("info.version = %q, want 0.x", got)
	}
	desc := strings.ToLower(docString(info, "description"))
	for _, want := range []string{"incomplete", "before v1", "--enable-api-key-management", "auth"} {
		if !strings.Contains(desc, want) {
			t.Errorf("info.description should mention %q: %q", want, desc)
		}
	}

	if got := docString(doc, "basePath"); got != "/api" {
		t.Errorf("basePath = %q, want /api", got)
	}
	assertAbsentOrEmpty(t, doc, "host", "")
	assertAbsentOrEmpty(t, doc, "schemes", []any{})
	assertAbsentOrEmpty(t, doc, "security", []any{})

	bearer := docObject(t, doc, "securityDefinitions", "BearerAuth")
	if docString(bearer, "type") != "apiKey" || docString(bearer, "in") != "header" || docString(bearer, "name") != "Authorization" {
		t.Errorf("BearerAuth = %v", bearer)
	}
	if !strings.Contains(docString(bearer, "description"), "Bearer lw_<prefix>_<secret>") {
		t.Errorf("BearerAuth description must show the full header value: %q", docString(bearer, "description"))
	}
}

func TestAPIDocs_Health_DocumentsPublicProbe(t *testing.T) {
	doc := readAPIDocument(t, "swagger.json")

	item := docObject(t, doc, "paths", "/health")
	if len(item) != 1 {
		t.Fatalf("/health operations = %v, want only get", reflect.ValueOf(item).MapKeys())
	}
	op := docObject(t, item, "get")

	if tags, _ := op["tags"].([]any); len(tags) != 1 || tags[0] != "health" {
		t.Errorf("tags = %v, want [health]", op["tags"])
	}
	if produces, _ := op["produces"].([]any); len(produces) != 1 || produces[0] != "application/json" {
		t.Errorf("produces = %v", op["produces"])
	}
	if _, ok := op["security"]; ok {
		t.Errorf("health must not require authentication: %v", op["security"])
	}
	if _, ok := op["consumes"]; ok {
		t.Errorf("health has no request body: consumes = %v", op["consumes"])
	}
	if params, _ := op["parameters"].([]any); len(params) != 0 {
		t.Errorf("health has no parameters: %v", params)
	}

	responses := docObject(t, op, "responses")
	if _, ok := responses["403"]; ok {
		t.Error("403 must not be documented for health")
	}

	// 200 -> health model, resolved by reference instead of an assumed name.
	name, health := resolveDefinition(t, doc, docObject(t, responses, "200", "schema"))
	if !strings.HasSuffix(name, "HealthResponse") {
		t.Errorf("200 references %q, want the HealthResponse model", name)
	}
	assertProperties(t, health, map[string]string{"status": "string", "checks": "object"})
	if add := docObject(t, docObject(t, health, "properties", "checks"), "additionalProperties"); docString(add, "type") != "string" {
		t.Errorf("checks additionalProperties = %v, want string", add)
	}

	// 401 and 429 -> flat error model.
	for _, status := range []string{"401", "429"} {
		name, legacy := resolveDefinition(t, doc, docObject(t, responses, status, "schema"))
		if !strings.HasSuffix(name, "LegacyError") {
			t.Errorf("%s references %q, want the LegacyError model", status, name)
		}
		assertProperties(t, legacy, map[string]string{"error": "string"})
	}

	// 503 -> intentionally broad object that names both real shapes.
	r503 := docObject(t, responses, "503")
	schema := docObject(t, r503, "schema")
	if docString(schema, "type") != "object" {
		t.Errorf("503 schema type = %v, want object", schema["type"])
	}
	if _, ok := schema["$ref"]; ok {
		t.Errorf("503 schema must not reference a single model: %v", schema)
	}
	for _, want := range []string{"HealthResponse", "LegacyError"} {
		if !strings.Contains(docString(r503, "description"), want) {
			t.Errorf("503 description should name %s: %q", want, docString(r503, "description"))
		}
	}
}

// assertProperties requires the model to have exactly the wanted properties
// (name -> type): an extra field is a wire-format change that the annotation
// must not hide. An empty wanted type accepts any type, for properties that
// reference another model.
func assertProperties(t *testing.T, model map[string]any, want map[string]string) {
	t.Helper()
	props := docObject(t, model, "properties")
	for name := range props {
		if _, ok := want[name]; !ok {
			t.Errorf("unexpected property %q", name)
		}
	}
	for name, wantType := range want {
		prop := docObject(t, props, name)
		if got := docString(prop, "type"); wantType != "" && got != wantType {
			t.Errorf("property %q type = %q, want %q", name, got, wantType)
		}
	}
}

// queryParam is the documented type and requiredness of a query parameter.
type queryParam struct {
	typ      string
	required bool
}

// opSpec is what one documented operation must say. Every expectation is
// explicit, so route kinds with other guards or bodies build their own spec;
// apiReadGroupGET fills in the read-group defaults.
type opSpec struct {
	method, path string
	// onlyOperation requires method to be the only operation on path.
	onlyOperation bool
	tag           string
	// bearer requires @Security BearerAuth (the route accepts API keys).
	bearer bool
	// descriptionMentions are lower-case phrases the description must contain.
	descriptionMentions []string
	// query and pathParams list every parameter of their kind; a nil map means
	// none. Any other kind of parameter fails the check.
	query      map[string]queryParam
	pathParams map[string]queryParam
	// arrayOf is the model suffix of the 200 array items, with its properties.
	// An operation answering with an object sets okRef and okProps instead.
	arrayOf      string
	arrayOfProps map[string]string
	okRef        string
	okProps      map[string]string
	// refs maps a status to the model suffix its schema references.
	refs map[string]string
	// broad maps a status with several real shapes to the model names its
	// description must name; its schema must be a plain object.
	broad map[string][]string
	// absent lists statuses that must not be documented.
	absent []string
}

// apiReadGroupGET is the spec of a GET behind RouterContext.APIReadGroup:
// API keys and cookies accepted, anonymous reads with public access on,
// localized 400s from the handler, flat 401/429/503 from the auth and API-key
// middleware, a 500 that is localized from the handler or flat from the
// middleware, and no 403 (CSRF does nothing on GET and there is no role guard).
func apiReadGroupGET(path, tag string) opSpec {
	return opSpec{
		method:              "get",
		path:                path,
		onlyOperation:       true,
		tag:                 tag,
		bearer:              true,
		descriptionMentions: []string{"public access", "cookie"},
		refs:                map[string]string{"400": "ErrorResponse", "401": "LegacyError", "429": "LegacyError", "503": "LegacyError"},
		broad:               map[string][]string{"500": {"ErrorResponse", "LegacyError"}},
		absent:              []string{"403"},
	}
}

// assertParams compares the documented parameters of one kind with the wanted
// ones; a nil and an empty map both mean "no parameters".
func assertParams(t *testing.T, kind string, got, want map[string]queryParam) {
	t.Helper()
	if len(got) == 0 && len(want) == 0 {
		return
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("%s parameters = %v, want %v", kind, got, want)
	}
}

// assertOperation checks one documented operation against its spec.
func assertOperation(t *testing.T, doc map[string]any, spec opSpec) {
	t.Helper()
	item := docObject(t, doc, "paths", spec.path)
	if spec.onlyOperation && len(item) != 1 {
		t.Errorf("%s operations = %v, want only %s", spec.path, reflect.ValueOf(item).MapKeys(), spec.method)
	}
	op := docObject(t, item, spec.method)

	if tags, _ := op["tags"].([]any); len(tags) != 1 || tags[0] != spec.tag {
		t.Errorf("tags = %v, want [%s]", op["tags"], spec.tag)
	}
	security, hasSecurity := op["security"].([]any)
	switch {
	case spec.bearer && (len(security) != 1 || docObject(t, security[0].(map[string]any))["BearerAuth"] == nil):
		t.Errorf("security = %v, want BearerAuth", op["security"])
	case !spec.bearer && hasSecurity:
		t.Errorf("security = %v, want none", op["security"])
	}
	desc := strings.ToLower(docString(op, "description"))
	for _, want := range spec.descriptionMentions {
		if !strings.Contains(desc, want) {
			t.Errorf("description should mention %q: %q", want, desc)
		}
	}

	gotQuery := map[string]queryParam{}
	gotPath := map[string]queryParam{}
	params, _ := op["parameters"].([]any)
	for _, raw := range params {
		p := raw.(map[string]any)
		required, _ := p["required"].(bool)
		param := queryParam{docString(p, "type"), required}
		switch in := docString(p, "in"); in {
		case "query":
			gotQuery[docString(p, "name")] = param
		case "path":
			gotPath[docString(p, "name")] = param
		default:
			t.Errorf("parameter %v is in %q, want query or path", p, in)
		}
	}
	assertParams(t, "query", gotQuery, spec.query)
	assertParams(t, "path", gotPath, spec.pathParams)

	responses := docObject(t, op, "responses")
	ok := docObject(t, responses, "200", "schema")
	if spec.okRef != "" {
		name, model := resolveDefinition(t, doc, ok)
		if !strings.HasSuffix(name, spec.okRef) {
			t.Errorf("200 references %q, want %s", name, spec.okRef)
		}
		assertProperties(t, model, spec.okProps)
	} else {
		if docString(ok, "type") != "array" {
			t.Fatalf("200 schema = %v, want an array", ok)
		}
		name, model := resolveDefinition(t, doc, docObject(t, ok, "items"))
		if !strings.HasSuffix(name, spec.arrayOf) {
			t.Errorf("200 items reference %q, want %s", name, spec.arrayOf)
		}
		assertProperties(t, model, spec.arrayOfProps)
	}

	for status, want := range spec.refs {
		if name, _ := resolveDefinition(t, doc, docObject(t, responses, status, "schema")); !strings.HasSuffix(name, want) {
			t.Errorf("%s references %q, want %s", status, name, want)
		}
	}
	for status, names := range spec.broad {
		resp := docObject(t, responses, status)
		if schema := docObject(t, resp, "schema"); docString(schema, "type") != "object" || schema["$ref"] != nil {
			t.Errorf("%s schema = %v, want a broad object", status, schema)
		}
		for _, want := range names {
			if !strings.Contains(docString(resp, "description"), want) {
				t.Errorf("%s description should name %s: %q", status, want, docString(resp, "description"))
			}
		}
	}
	for _, status := range spec.absent {
		if _, ok := responses[status]; ok {
			t.Errorf("%s must not be documented", status)
		}
	}
}

